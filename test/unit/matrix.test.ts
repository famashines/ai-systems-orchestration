test("the inputs of the matrix are every run command, steer, answer, CompleteCall and FailCall", () => {
  assert.deepEqual(
    inputs.map(([name]) => name),
    [
      "StartRun",
      "PauseRun",
      "ResumeRun",
      "CancelRun",
      "CancelTask",
      "RetrySubtask",
      "ResolveCheckpoint",
      "CheckpointDue",
      "RetryDue",
      "steer",
      "answer",
      "CompleteCall",
      "FailCall",
    ],
  );
});

for (const variant of ["plan", "chat"] as const) {
  for (const state of states) {
    test(`decide matrix, ${variant} task, ${state}: each input gives its events or a conflict`, () => {
      const events = history(variant === "plan", state);
      assert.deepEqual(
        inputs.map(([name, command]) => `${name}: ${cell(events, command)}`),
        inputs.map(([name], index) => `${name}: ${expected[variant][state]?.[index] ?? "missing"}`),
      );
    });
  }
}
